 check('Cancellation never claims refund',lambda:must(all(x['refunded'] is False for x in responses)))
 check('Order detail history preserved',lambda:must(a.call('MemberOrders?orderID='+str(order))[0]['seat']=='A01'))
 first_time=sql(f'SELECT cancelledAt FROM local_simulation_order WHERE orderID={order};')
 check('Cancellation timestamp persisted',lambda:must(bool(first_time) and first_time!='NULL'))
 check('Original allocation removed',lambda:must(not allocated('A01') and status(b,'A01')=='available'))
 check('Other owned order allocation untouched',lambda:must(bool(allocated('A02')) and orderstate(used)==3))
