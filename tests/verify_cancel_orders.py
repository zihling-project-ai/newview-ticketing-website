def cancel(c,order,expected=200,**extra):return c.call('CancelLocalOrder',dict(orderID=order,confirmCancellation='true',**extra),expected=expected)
def buy(c,seat):
 hold(c,seat);request=key(c);result=checkout(c,request);return result['orderIDs'][0],request
