 check('Cancelled seat available after Redis restarts',lambda:must(status(b,'A04')=='available'))
 check('Other members allocation survives cancellation and restart',lambda:must(status(b,'A01')=='booked' and allocated('A01')==new_ticket))
 summary=next(x for x in a.call('MemberOrders') if x['orderID']==order)
 check('Member list exposes cancelled status and timestamp',lambda:must(summary['ordType']==2 and bool(summary['cancelledAt'])))
