 check('Quantity-only mock order cancellation supported',lambda:must(result['releasedSeats']==0 and orderstate(quantity)==2))
 check('Quantity-only cancelled detail remains available',lambda:must(len(a.call('MemberOrders?orderID='+str(quantity)))==2))
